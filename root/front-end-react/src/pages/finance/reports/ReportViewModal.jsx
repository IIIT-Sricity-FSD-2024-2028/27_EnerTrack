/**
 * ReportViewModal — read-only details of a financial report.
 * Also used by the Archives page (it passes archived = true).
 */
import Badge from "../components/Badge";
import Modal from "../components/Modal";
import { formatCurrency, formatDate } from "../financeUtils";

export default function ReportViewModal({ report, archived = false, onClose }) {
  return (
    <Modal
      title={archived ? `${report.title} (Archived)` : report.title}
      confirmLabel="Close"
      cancelLabel=""
      onClose={onClose}
    >
      <div className="fa-detail-grid">
        <div><strong>Period</strong><p>{report.period}</p></div>
        <div><strong>Category</strong><p style={{ textTransform: "capitalize" }}>{report.category}</p></div>
        <div><strong>Scope</strong><p>{report.scopeLabel}</p></div>
        <div><strong>Format</strong><p>{report.format}</p></div>
        <div><strong>ROI</strong><p>{report.roi != null ? report.roi + "%" : "—"}</p></div>
        <div><strong>NPV</strong><p>{report.npv != null ? formatCurrency(report.npv) : "—"}</p></div>
        <div><strong>Payback Period</strong><p>{report.paybackYears != null ? report.paybackYears + " yrs" : "—"}</p></div>
        <div><strong>Status</strong><p><Badge status={report.status} /></p></div>
        {!archived && (
          <>
            <div><strong>Generated By</strong><p>{report.generatedBy}</p></div>
            <div><strong>Generated At</strong><p>{formatDate(report.generatedAt)}</p></div>
          </>
        )}
      </div>
      <div className="fa-detail-notes">
        <strong>Notes:</strong> {report.notes || "—"}
      </div>
    </Modal>
  );
}
